//go:build windows

package hub

import "golang.org/x/sys/windows"

// diskFree reports the bytes available to the hub process on the volume
// holding dir.
func diskFree(dir string) (uint64, error) {
	p, err := windows.UTF16PtrFromString(dir)
	if err != nil {
		return 0, err
	}
	var free uint64
	if err := windows.GetDiskFreeSpaceEx(p, &free, nil, nil); err != nil {
		return 0, err
	}
	return free, nil
}
